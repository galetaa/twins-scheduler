#!/usr/bin/env python3
"""Generate the reviewer map from current claim IDs, never stale theorem numbers."""
from pathlib import Path
import csv
import sys
ROOT = Path(__file__).resolve().parents[1]
with (ROOT/'docs/CLAIM_EVIDENCE_LEDGER.csv').open(newline='') as f:
    claims = {row['id']: row for row in csv.DictReader(f)}
requirements = [
    ('Exact static-policy refinement', ['C23']),
    ('General finite-model optimum and independent certificate', ['C24','C25']),
    ('Detailed-model transfer and whole-policy elimination', ['C26','C27']),
    ('Corrected persistence and irreversible-output mechanism', ['C2','C11','C12']),
    ('Full guarded four-validator trace and timing controls', ['C13']),
    ('Coupled protocol export and independent checking', ['C29','C30','C34']),
    ('Larger protocol / six dependent controls / full refinement costs', ['C36']),
    ('Structural specialization, not a universal pivot assumption', ['C18','C33']),
    ('Replay relegated to a supporting result', ['C6','C7']),
    ('Mechanized versus executable assurance boundaries', ['C10','C35']),
    ('Native unchanged-client conformance, not a native exploit', ['C22']),
]
lines=['# Reviewer completion matrix','',
       'Generated by `python scripts/sync_review_matrix.py` from `docs/CLAIM_EVIDENCE_LEDGER.csv`.',
       'Check without modifying: `python scripts/sync_review_matrix.py --check`.',
       'Historical artifact identifiers are not current theorem numbers. Statuses below are those recorded in the ledger; fresh run logs are separate evidence.','',
       '| Reviewer requirement | Current claim IDs | Current manuscript location | Recorded evidence status |',
       '|---|---|---|---|']
for title, ids in requirements:
    rows=[claims[x] for x in ids]
    locations='; '.join(dict.fromkeys(x['paper_location'] for x in rows))
    statuses='; '.join(dict.fromkeys(x['status'] for x in rows))
    lines.append(f"| {title} | {', '.join(ids)} | {locations} | {statuses} |")
lines += ['', '## Editorial and practical completion', '',
    '| Requirement | Implemented correction / check |', '|---|---|',
    '| Definite student-award status | Both covers: not nominated (eligibility not claimed); student enrollment is recorded separately. See AUTHOR_METADATA.md. |',
    '| Author details | Mikhail Alexandrovich Galeta; SUAI, Saint Petersburg. No invented email or ORCID. |',
    '| Literal PDF reference tildes | Markdown raw-LaTeX reference spans; PDF text check rejects literal tildes and unresolved references. |',
    '| Reviewer numbering | Current main Theorems 1–6 follow C23–C27 and C18/C33; preserved earlier propositions stay in Appendices B/E. |',
    '| Novelty / utility | Section 7.2 distinguishes established CEGAR/minimal revision from the persistent-policy cost and evidence contract; Section 6.3 demonstrates instrumentation choice and bounded infeasibility. |',
    '| Reproduction | Full wrapper includes scaled study and deterministic comparison; both named and anonymous PDFs are compiled. |',
    '', 'The exact scope and prohibited extensions are in [the claim ledger](../CLAIM_EVIDENCE_LEDGER.md).', '']
expected='\n'.join(lines)
path=ROOT/'docs/reviews/REVIEWER_COMPLETION_MATRIX.md'
if '--check' in sys.argv:
    if not path.exists() or path.read_text()!=expected:
        raise SystemExit('REVIEWER MATRIX FAIL: regenerate from the claim ledger')
    print('REVIEWER MATRIX PASS: current claim IDs and locations')
else:
    path.write_text(expected)
